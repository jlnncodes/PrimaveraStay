    private void loadReservations() {
    cmbReservation.removeAllItems();
    cmbReservation.addItem("Select Reservation");

    String sql = "SELECT reservation_id, guest_name "
            + "FROM reservations "
            + "WHERE reservation_status <> 'Cancelled' "
            + "AND is_archived = 0 "
            + "ORDER BY reservation_id DESC";

    try (java.sql.Connection conn =
            DatabaseConnection.getConnection();
         java.sql.PreparedStatement stmt =
            conn.prepareStatement(sql);
         java.sql.ResultSet rs = stmt.executeQuery()) {

        while (rs.next()) {
            int id = rs.getInt("reservation_id");
            String guest = rs.getString("guest_name");

            cmbReservation.addItem(id + " - " + guest);
        }

    } catch (java.sql.SQLException e) {
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Error loading reservations: " + e.getMessage()
        );
    }
}

