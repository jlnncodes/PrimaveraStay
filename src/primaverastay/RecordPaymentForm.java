    private void btnSavePaymentActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSavePaymentActionPerformed
        try {
    if (loggedInUser == null) {
        JOptionPane.showMessageDialog(this,
                "No admin account is logged in.");
        return;
    }

    if (cmbReservation.getSelectedIndex() <= 0
            || cmbPaymentType.getSelectedIndex() <= 0
            || cmbPaymentMethod.getSelectedIndex() <= 0) {

        JOptionPane.showMessageDialog(this,
                "Please complete all required fields.");
        return;
    }

    String reservationText =
            cmbReservation.getSelectedItem().toString();

    int reservationId = Integer.parseInt(
            reservationText.split(" - ", 2)[0]
    );

    java.math.BigDecimal amount =
            new java.math.BigDecimal(txtAmount.getText().trim());

    if (amount.compareTo(java.math.BigDecimal.ZERO) <= 0) {
        JOptionPane.showMessageDialog(this,
                "Amount must be greater than zero.");
        return;
    }

    String balanceSql =
        "SELECT r.total_amount - COALESCE(("
        + "SELECT SUM(p.amount) FROM payments p "
        + "WHERE p.reservation_id = r.reservation_id "
        + "AND p.payment_status IN ('Pending', 'Verified')"
        + "), 0) AS remaining_balance "
        + "FROM reservations r WHERE r.reservation_id = ?";

try (java.sql.Connection conn =
        DatabaseConnection.getConnection();
     java.sql.PreparedStatement stmt =
        conn.prepareStatement(balanceSql)) {

    stmt.setInt(1, reservationId);

    try (java.sql.ResultSet rs = stmt.executeQuery()) {

        if (!rs.next()) {
            JOptionPane.showMessageDialog(this,
                    "Reservation not found.");
            return;
        }

        java.math.BigDecimal remaining =
                rs.getBigDecimal("remaining_balance");

        if (amount.compareTo(remaining) > 0) {
            JOptionPane.showMessageDialog(this,
                    "Amount exceeds the remaining balance: PHP "
                    + remaining);
            return;
        }
    }

} catch (java.sql.SQLException e) {
    JOptionPane.showMessageDialog(this,
            "Unable to check balance: " + e.getMessage());
    return;
}
    
    String paymentType =
            cmbPaymentType.getSelectedItem().toString();

    String paymentMethod =
            cmbPaymentMethod.getSelectedItem().toString();

    String referenceNumber =
            txtReferenceNumber.getText().trim();

    PaymentDAO dao = new PaymentDAO();

    boolean saved = dao.savePayment(
            reservationId,
            amount,
            paymentType,
            paymentMethod,
            referenceNumber,
            loggedInUser.getUserId()
    );

    if (saved) {
        JOptionPane.showMessageDialog(this,
                "Payment recorded successfully! Status: Pending");
        dispose();
    }

} catch (NumberFormatException e) {
    JOptionPane.showMessageDialog(this,
            "Please enter a valid payment amount.");
}
    }//GEN-LAST:event_btnSavePaymentActionPerformed

